import type { PurchaseInvoice, PurchaseLineItem } from '../../types/purchase'

function makePurchaseLine(
  id: string, description: string, hsnSac: string,
  quantity: number, unit: string, rate: number, discountPercent: number,
  gstRate: number, supplyType: 'intra' | 'inter', itcEligible: boolean
): PurchaseLineItem {
  const baseAmount = quantity * rate
  const discountAmount = baseAmount * discountPercent / 100
  const taxableValue = Math.round((baseAmount - discountAmount) * 100) / 100
  const gstAmount = Math.round(taxableValue * gstRate / 100 * 100) / 100
  const cgst = supplyType === 'intra' ? Math.round(gstAmount / 2 * 100) / 100 : 0
  const sgst = supplyType === 'intra' ? Math.round(gstAmount / 2 * 100) / 100 : 0
  const igst = supplyType === 'inter' ? gstAmount : 0
  return { id, description, hsnSac, quantity, unit, rate, discountPercent, taxableValue, gstRate, cgst, sgst, igst, totalAmount: Math.round((taxableValue + gstAmount) * 100) / 100, itcEligible }
}

